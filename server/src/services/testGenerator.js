import { GoogleGenerativeAI } from '@google/generative-ai';

/**
 * Unit Test Case Generator Service
 */
export async function generateTestCases({ code, language = 'javascript', apiKey = null, framework = 'auto' }) {
  const activeApiKey = apiKey || process.env.GEMINI_API_KEY;

  if (!activeApiKey) {
    return generateOfflineTestCases(code, language);
  }

  try {
    const genAI = new GoogleGenerativeAI(activeApiKey);
    const model = genAI.getGenerativeModel({ model: 'gemini-2.0-flash' });

    const prompt = `
Generate a comprehensive, production-ready unit test suite for the following ${language} code.
Ensure you test:
1. Standard / Happy Path cases
2. Edge cases (null/undefined/empty input, 0, negative values, large bounds)
3. Exception / Error condition paths

Framework: ${framework === 'auto' ? `Standard framework for ${language}` : framework}

Return ONLY the code for the test file without markdown explanations.

Code:
\`\`\`${language}
${code}
\`\`\`
`;

    const result = await model.generateContent(prompt);
    let tests = result.response.text();
    // Clean markdown code blocks if any
    tests = tests.replace(/^```[a-zA-Z]*\n/, '').replace(/\n```$/, '').trim();

    return {
      success: true,
      tests,
      framework: framework === 'auto' ? getDefaultFramework(language) : framework
    };
  } catch (err) {
    console.warn('[Test Generator] AI generation failed, using template generator:', err.message);
    return generateOfflineTestCases(code, language);
  }
}

function getDefaultFramework(language) {
  const lang = language.toLowerCase();
  if (['python', 'py'].includes(lang)) return 'pytest';
  if (['javascript', 'typescript', 'js', 'ts'].includes(lang)) return 'Jest / Vitest';
  if (['cpp', 'c++'].includes(lang)) return 'GoogleTest';
  if (['go', 'golang'].includes(lang)) return 'Go testing';
  if (['java'].includes(lang)) return 'JUnit 5';
  return 'Standard Assertions';
}

